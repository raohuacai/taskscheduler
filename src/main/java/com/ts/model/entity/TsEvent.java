package com.ts.model.entity;

import java.util.Date;

/**
 * Entity class for the TS_EVENT table.
 * Represents the full lifecycle record of an event that an EventTask waits on.
 *
 * Status transitions:
 *   NEW       – row created by upstream task (e.g. HttpTask.postAction)
 *   WAITING   – EventTask has started blocking on the in-memory latch
 *   TRIGGERED – trigger API was called; EventTask has been (or will be) unblocked
 *
 * Author: Rock Rao
 * Date: 2025
 * Version: 1.0
 */
public class TsEvent {

    /** Surrogate PK – numeric UUID generated by UniqueIdGenerator. */
    private String id;

    /** Globally unique business event key. */
    private String eventKey;

    /**
     * Top-parent workflow instance ID.
     * Propagated through sub-workflow chains via
     * Constants.PARAM_TOP_PARENT_WORKFLOW_INSTANCE.
     */
    private String tpwfInstanceId;

    /** Task definition ID of the EventTask node in the workflow. */
    private String taskId;

    /** Current lifecycle status: NEW | WAITING | TRIGGERED. */
    private String status;

    /** JSON payload supplied by the trigger caller; null until TRIGGERED. */
    private String payload;

    /** Username of the API caller who fired the trigger. */
    private String triggeredBy;

    /** Row creation timestamp (Java Date, set when status = NEW). */
    private Date creationDate;

    /** Timestamp when EventTask set status to WAITING (Java Date). */
    private Date waitDate;

    /** Timestamp when the trigger API was called (Java Date). */
    private Date triggeredDate;

    // ── Getters / Setters ──────────────────────────────────────────────────────

    /** Returns the unique event record ID. */
    public String getId() { return id; }
    public void setId(String id) { this.id = id; }

    public String getEventKey() { return eventKey; }
    public void setEventKey(String eventKey) { this.eventKey = eventKey; }

    public String getTpwfInstanceId() { return tpwfInstanceId; }
    public void setTpwfInstanceId(String tpwfInstanceId) { this.tpwfInstanceId = tpwfInstanceId; }

    public String getTaskId() { return taskId; }
    public void setTaskId(String taskId) { this.taskId = taskId; }

    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }

    public String getPayload() { return payload; }
    /**
     * Sets the trigger payload — an arbitrary JSON or plain-text string supplied
     * by the triggering party and made available to the waiting {@link com.ts.task.core.EventTask}.
     *
     * @param payload  the trigger payload; may be {@code null} if no data needs to be passed
     */
    public void setPayload(String payload) { this.payload = payload; }

    public String getTriggeredBy() { return triggeredBy; }
    public void setTriggeredBy(String triggeredBy) { this.triggeredBy = triggeredBy; }

    public Date getCreationDate() { return creationDate; }
    public void setCreationDate(Date creationDate) { this.creationDate = creationDate; }

    public Date getWaitDate() { return waitDate; }
    public void setWaitDate(Date waitDate) { this.waitDate = waitDate; }

    public Date getTriggeredDate() { return triggeredDate; }
    public void setTriggeredDate(Date triggeredDate) { this.triggeredDate = triggeredDate; }

    @Override
    public String toString() {
        return "TsEvent{id='" + id
                + "', eventKey='" + eventKey
                + "', tpwfInstanceId='" + tpwfInstanceId
                + "', taskId='" + taskId
                + "', status='" + status
                + "', triggeredBy='" + triggeredBy
                + "', creationDate=" + creationDate
                + ", waitDate=" + waitDate
                + ", triggeredDate=" + triggeredDate + '}';
    }
}
