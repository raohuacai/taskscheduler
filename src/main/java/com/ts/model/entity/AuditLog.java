package com.ts.model.entity;

import java.util.Date;
/**
 * Entity representing one audit log entry recording who performed which operation.
 */
public class AuditLog {

    private String auditId;       // Generated by SeqIdGenerator.generateAuditId()
    private String operator;      // Operator (extracted from JWT; input username on login failure)
    private String operation;     // Operation type, e.g. CREATE_WORKFLOW_DEF
    private String module;        // Module name, e.g. WORKFLOW_DEF
    private String httpMethod;    // GET / POST / PUT / DELETE
    private String requestPath;   // Request path
    private String dataJson;      // Core business data (JSON, sanitised)
    private String result;        // SUCCESS / FAILURE
    private String errorMsg;      // Error message when FAILURE (trimmed to 1000 chars)
    private String clientIp;      // Client IP address
    private Date   operateTime;   // Operation timestamp

    /**
     * Returns the audit id.
     *
     * @param getRequestPath(  file-system path
     * @return the result as a String
     */
    public String getAuditId()                       { return auditId; }
    public void   setAuditId(String auditId)         { this.auditId = auditId; }

    public String getOperator()                      { return operator; }
    public void   setOperator(String operator)       { this.operator = operator; }

    public String getOperation()                     { return operation; }
    public void   setOperation(String operation)     { this.operation = operation; }

    public String getModule()                        { return module; }
    public void   setModule(String module)           { this.module = module; }

    public String getHttpMethod()                    { return httpMethod; }
    public void   setHttpMethod(String httpMethod)   { this.httpMethod = httpMethod; }

    public String getRequestPath()                   { return requestPath; }
    /**
     * Sets the HTTP request path recorded in this audit log entry.
     *
     * @param requestPath  the URL path of the audited request (e.g. {@code /api/definition/workflow})
     */
    public void   setRequestPath(String requestPath) { this.requestPath = requestPath; }

    public String getDataJson()                      { return dataJson; }
    public void   setDataJson(String dataJson)       { this.dataJson = dataJson; }

    public String getResult()                        { return result; }
    public void   setResult(String result)           { this.result = result; }

    public String getErrorMsg()                      { return errorMsg; }
    public void   setErrorMsg(String errorMsg)       { this.errorMsg = errorMsg; }

    public String getClientIp()                      { return clientIp; }
    public void   setClientIp(String clientIp)       { this.clientIp = clientIp; }

    public Date getOperateTime()                     { return operateTime; }
    public void setOperateTime(Date operateTime)     { this.operateTime = operateTime; }
}
